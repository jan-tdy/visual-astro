type Key = keyof (typeof dict)["sk"];

// Translations are loaded at runtime from Tolgee Content Delivery (public,
// read-only CDN — no admin/personal API key in the browser). Edit strings in
// Tolgee and hit "Publish" on the Content Delivery config to push them live.
// Set this to your Content Delivery URL, e.g. "https://cdn.tolg.ee/<id>".
const TOLGEE_CDN_URL: string =
  (import.meta.env.VITE_TOLGEE_CDN_URL as string | undefined) ??
  "https://cdn.tolg.ee/aa59fd475e54efc1943b6669f398d193";

// Map our short app lang codes to Tolgee project language tags
const TOLGEE_MAP: Record<Lang, string> = {
  sk: "sk-SK",
  en: "en",
  cs: "cs-CZ",
  de: "de-DE",
  es: "es-ES",
  fr: "fr",
  it: "it",
  pl: "pl",
};
const toTolgee = (l: string) => TOLGEE_MAP[l as Lang] ?? "en";
const fromTolgee = (t: string): Lang => {
  const entry = (Object.entries(TOLGEE_MAP) as [Lang, string][]).find(([, v]) => v === t);
  return entry?.[0] ?? (t.split("-")[0] as Lang) ?? "sk";
};

const storedLang = (): Lang => {
  if (typeof window === "undefined") return "sk";
  const s = localStorage.getItem("lang") || "sk";
  return (SUPPORTED_LANGS.some((l) => l.code === s) ? s : "sk") as Lang;
};

let builder = Tolgee();
if (TOLGEE_CDN_URL) {
  builder = builder.use(
    BackendFetch({ prefix: TOLGEE_CDN_URL.replace(/\/$/, ""), fallbackOnFail: true }),
  );
}

const tolgee = builder.use(FormatSimple()).init({
  language: toTolgee(storedLang()),
  defaultLanguage: "sk-SK",
  fallbackLanguage: "sk-SK",
  availableLanguages: SUPPORTED_LANGS.map((l) => toTolgee(l.code)),
  // in-app fallback so the UI never renders raw keys if the CDN is unreachable
  staticData: {
    "sk-SK": dict.sk as unknown as Record<string, string>,
    en: dict.en as unknown as Record<string, string>,
  },
});

interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: Key | string) => string;
}

const I18nCtx = createContext<Ctx | null>(null);

function InnerProvider({ children }: { children: ReactNode }) {
  const tg = useTolgee(["language"]);
  const { t: tTrans } = useTranslate();
  const lang = fromTolgee(tg.getLanguage() || "sk-SK");

  useEffect(() => {
    localStorage.setItem("lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang: (l: Lang) => {
        tg.changeLanguage(toTolgee(l));
      },
      t: (k) => {
        const key = k as string;
        const v = tTrans(key);
        const normalized = v?.replace(/[\u200B-\u200D\uFEFF]/g, "") ?? "";
        const skText = (dict.sk as Record<string, string>)[key];
        const enText = (dict.en as Record<string, string>)[key];
        if (v && normalized !== key && !normalized.includes(key)) {
          // Tolgee can silently fall back to a *different* language's static data
          // when a key has no translation yet for the current one (e.g. a brand
          // new sk-SK key falls through to our own "en" staticData). Catch that
          // specific case and prefer our own dict for the current language
          // instead -- but otherwise trust Tolgee's result, since sk/en labels
          // are user-editable there (e.g. renamed nav tab labels).
          if (lang === "sk" && v === enText && skText) return skText;
          if (lang === "en" && v === skText && enText) return enText;
          return v;
        }
        // Fallback when a key isn't published for the current language yet:
        // English is far more widely understood than Slovak as a second-best guess.
        const base = lang === "sk" ? skText : lang === "en" ? enText : undefined;
        return base ?? enText ?? skText ?? key;
      },
    }),
    [lang, tg, tTrans],
  );

  return <I18nCtx.Provider value={value}>{children}</I18nCtx.Provider>;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  return (
    <TolgeeProvider tolgee={tolgee} fallback="Loading…">
      <InnerProvider>{children}</InnerProvider>
    </TolgeeProvider>
  );
}

export function useI18n() {
  const c = useContext(I18nCtx);
  if (!c) throw new Error("useI18n must be used within I18nProvider");
  return c;
}